def compute_metrics(rows: list[dict[str, Any]]) -> dict[str, Any]:
    def subset(*classes: str) -> list[dict[str, Any]]:
        wanted = set(classes)
        out = []
        for r in rows:
            cls = (r.get("outcome") or {}).get("label_class") or (r.get("label") or {}).get("class")
            if cls in wanted:
                out.append(r)
        return out

    def counts(rs: list[dict[str, Any]]) -> dict[str, int]:
        c = {"TP": 0, "FP": 0, "TN": 0, "FN": 0, "ERROR": 0, "UNEXPECTED_FAIL": 0, "OTHER": 0}
        for r in rs:
            v = (r.get("outcome") or {}).get("verdict", "OTHER")
            if v in c:
                c[v] += 1
            else:
                c["OTHER"] += 1
        return c

    pos = subset("objective_slop", "synthetic_positive")
    neg = subset("merged_control", "synthetic_negative")
    sample = subset("closed_unmerged_sample")
    pos_c = counts(pos)
    neg_c = counts(neg)
    sample_c = counts(sample)
    tp, fn = pos_c["TP"], pos_c["FN"]
    fp, tn = neg_c["FP"], neg_c["TN"]
    sample_n = sum(sample_c.values()) - sample_c["ERROR"]
    precision = (tp / (tp + fp)) if (tp + fp) else None
    recall = (tp / (tp + fn)) if (tp + fn) else None
    return {
        "positives": pos_c,
        "negatives_controls": neg_c,
        "closed_unmerged_sample": sample_c,
        "hard_gate_precision": precision,
        "hard_gate_recall_on_labeled_positives": recall,
        "false_positive_rate_on_controls": (fp / (fp + tn)) if (fp + tn) else None,
        "closed_unmerged_hard_flag_rate": (sample_c["FP"] / sample_n) if sample_n else None,
        "n_cases": len(rows),
        "n_errors": sum(1 for r in rows if (r.get("outcome") or {}).get("verdict") == "ERROR"),
    }


