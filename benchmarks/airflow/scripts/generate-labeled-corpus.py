#!/usr/bin/env python3
"""
Generate a 50-case labeled bench corpus: 5 proper / 30 ai-slop / 15 mixed.

Writes:
  fixtures/labeled/** 
  corpus/cases-labeled-50.json

Ground truth is explicit — use this for product-value claims (precision/recall/FP),
not the unlabeled Airflow closed-unmerged census rate.
"""
from __future__ import annotations

import json
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BENCH = ROOT / "benchmarks" / "airflow"
FIX = BENCH / "fixtures" / "labeled"
CORPUS = BENCH / "corpus" / "cases-labeled-50.json"


def write(rel: str, body: str) -> str:
    path = FIX / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(body).lstrip() + "\n", encoding="utf-8")
    return f"fixtures/labeled/{rel.replace(chr(92), '/')}"


def clean_operator(n: int, name: str) -> str:
    return f'''
    """Clean control operator #{n}: {name}."""

    class {name}Error(Exception):
        def __init__(self, message: str, path: str | None = None):
            super().__init__(message)
            self.path = path


    def format_{name.lower()}_error(exc: Exception, path: str) -> str:
        if isinstance(exc, {name}Error) and getattr(exc, "path", None):
            return f"{{exc}} (path={{exc.path}})"
        return f"{{exc}} while accessing {{path}}"


    def validate_{name.lower()}_path(path: str) -> str:
        if not path or path.strip() == "":
            raise {name}Error("empty path")
        return path.replace("\\\\", "/")
    '''


def case(
    cid: str,
    label_class: str,
    expect_hard: bool,
    title: str,
    files: list[str],
    *,
    expect_advisory: bool = False,
    notes: str = "",
    subtype: str = "",
) -> dict:
    return {
        "id": cid,
        "source": "fixture",
        "path": files[0],
        "paths": files,
        "title": title,
        "label": {
            "class": label_class,
            "subtype": subtype,
            "expect_hard_fail": expect_hard,
            "expect_advisory": expect_advisory,
            "notes": notes,
        },
    }


def main() -> None:
    if FIX.exists():
        for p in FIX.rglob("*"):
            if p.is_file():
                p.unlink()
    FIX.mkdir(parents=True, exist_ok=True)

    cases: list[dict] = []

    # --- 5 proper (expect PASS) ---
    proper_names = ["Sftp", "Http", "Jdbc", "Kafka", "Redis"]
    for i, name in enumerate(proper_names, 1):
        rel = f"proper/proper-{i:02d}_{name.lower()}.py"
        write(rel, clean_operator(i, name))
        cases.append(
            case(
                f"proper-{i:02d}",
                "synthetic_negative",
                False,
                f"proper: clean {name} helper (expect PASS)",
                [f"fixtures/labeled/{rel}"],
                subtype="clean_control",
                notes="Hand-written clean control; hard-fail = FP",
            )
        )

    # --- 30 ai-slop (expect FAIL) ---
    slop_specs = []
    # 8x edit-artifact / SEARCH-REPLACE
    for i in range(1, 9):
        slop_specs.append(
            (
                f"slop-edit-{i:02d}",
                "edit_artifact",
                f"ai-slop/edit-{i:02d}.py",
                f'''
                """Synthetic AI-slop #{i}: incomplete edit paste."""

                def handler_{i}(callback):
                    # ... existing code unchanged ...
                    return callback
                ''',
            )
        )
    # 6x conflict markers
    for i in range(1, 7):
        slop_specs.append(
            (
                f"slop-conflict-{i:02d}",
                "merge_conflict",
                f"ai-slop/conflict-{i:02d}.py",
                f'''
                """Synthetic merge conflict leftover #{i}."""

                <<<<<<< HEAD
                def run_{i}_v1():
                    return 1
                =======
                def run_{i}_v2():
                    return 2
                >>>>>>> branch
                ''',
            )
        )
    # 6x attribution / Generated-by
    for i in range(1, 7):
        marker = [
            'MSG = "Generated by ChatGPT"',
            'MSG = "Generated by Claude"',
            "Generated-by: ChatGPT\nx = 1",
            'NOTE = "AI-generated scaffolding"',
            'MSG = "Generated by Copilot"',
            'MSG = "as an AI language model I suggest"',
        ][i - 1]
        slop_specs.append(
            (
                f"slop-attr-{i:02d}",
                "attribution",
                f"ai-slop/attr-{i:02d}.py",
                f'''
                """Synthetic AI attribution marker #{i}."""

                {marker}

                def noop_{i}():
                    return True
                ''',
            )
        )
    # 5x placeholders / YOUR_CODE
    for i in range(1, 6):
        body = [
            "def f():\n    # FIXME: finish this\n    return 1\n",
            "def f():\n    # TBD implement\n    pass\n",
            "def f():\n    YOUR_CODE_HERE\n",
            "def f():\n    INSERT_YOUR_CODE\n",
            "def f():\n    # XXX hack\n    return 0\n",
        ][i - 1]
        slop_specs.append(
            (
                f"slop-ph-{i:02d}",
                "placeholder",
                f"ai-slop/placeholder-{i:02d}.py",
                f'"""Synthetic placeholder / insert-code #{i}."""\n\n{body}',
            )
        )
    # 5x cohesion sprawl (multi-file multi-area) — hard-fail only if severity=fail;
    # Airflow bench uses warn, so mark expect_hard_fail False but expect_advisory True
    # Wait - user wants block metrics. For cohesion we use warn. Put cohesion in MIXED
    # as advisory. Use remaining 5 slots for SEARCH/REPLACE hard fails.

    for i in range(1, 6):
        slop_specs.append(
            (
                f"slop-search-{i:02d}",
                "search_replace",
                f"ai-slop/search-{i:02d}.py",
                f'''
                """Synthetic assistant SEARCH/REPLACE block #{i}."""

                # <<<<<<< SEARCH
                # old_fn_{i}()
                # =======
                # new_fn_{i}()
                # >>>>>>> REPLACE

                def keep_{i}():
                    return {i}
                ''',
            )
        )

    assert len(slop_specs) == 30, len(slop_specs)
    for cid, subtype, rel, body in slop_specs:
        write(rel, body)
        cases.append(
            case(
                cid,
                "synthetic_positive",
                True,
                f"ai-slop: {subtype} (expect FAIL)",
                [f"fixtures/labeled/{rel}"],
                subtype=subtype,
                notes="Labeled objective AI-slop; hard-pass = FN",
            )
        )

    # --- 15 mixed ---
    # 5 cohesion sprawl (advisory warn, hard PASS expected with severity=warn)
    for i in range(1, 6):
        tree_rel = f"mixed/cohesion-{i:02d}/tree"
        files = []
        for area, fname, body in [
            (
                ".github/workflows",
                f"wf-{i}.yml",
                f"name: bench-{i}\non: [push]\njobs:\n  j:\n    runs-on: ubuntu-latest\n    steps:\n      - run: echo {i}\n",
            ),
            (
                "scripts/ci",
                f"setup_{i}.py",
                f'"""CI setup helper {i}."""\n\ndef setup_{i}():\n    return {i}\n',
            ),
            (
                "scripts/tests",
                f"test_{i}.py",
                f'"""Test helper {i}."""\n\ndef test_{i}():\n    assert {i} == {i}\n',
            ),
            (
                "scripts/tools",
                f"tool_{i}.sh",
                f"#!/usr/bin/env bash\necho tool-{i}\n",
            ),
        ]:
            rel = f"{tree_rel}/{area}/{fname}"
            write(rel, body)
            files.append(f"fixtures/labeled/{rel}")
        cases.append(
            {
                "id": f"mixed-cohesion-{i:02d}",
                "source": "fixture",
                "path": files[0],
                "paths": files,
                "inject_tree": f"fixtures/labeled/{tree_rel}",
                "title": f"mixed: multi-area sprawl #{i} (expect PASS hard, advisory cohesion)",
                "label": {
                    "class": "mixed_sample",
                    "subtype": "cohesion_warn",
                    "expect_hard_fail": False,
                    "expect_advisory": True,
                    "notes": "Should trigger cohesion warn+label, not hard-fail",
                },
            }
        )

    # 5 mixed: mostly clean + buried soft density-ish large boilerplate (expect PASS hard)
    for i in range(1, 6):
        lines = [f'"""Mixed soft #{i}: verbose but valid."""', ""]
        lines.append(f"def compute_{i}(x: int) -> int:")
        for j in range(40):
            lines.append(f"    a{j} = x + {j}")
        lines.append(f"    return a0 + a39 + {i}")
        rel = f"mixed/soft/soft-{i:02d}.py"
        write(rel, "\n".join(lines) + "\n")
        cases.append(
            case(
                f"mixed-soft-{i:02d}",
                "mixed_sample",
                False,
                f"mixed: verbose clean code #{i} (expect PASS hard)",
                [f"fixtures/labeled/{rel}"],
                expect_advisory=False,
                subtype="verbose_clean",
                notes="May trip density advisory; hard-fail = FP",
            )
        )

    # 5 mixed: clean operator + one hard marker (expect FAIL) — "mixed quality"
    for i in range(1, 6):
        rel = f"mixed/hard/mixed-hard-{i:02d}.py"
        write(
            rel,
            f'''
            """Looks like a real fix but retains an AI artifact #{i}."""

            class Helper{i}:
                def run(self, path: str) -> str:
                    return path.replace("\\\\", "/")

            # ... rest of the existing code unchanged ...
            ''',
        )
        cases.append(
            case(
                f"mixed-hard-{i:02d}",
                "mixed_sample",
                True,
                f"mixed: otherwise-ok + edit-artifact #{i} (expect FAIL)",
                [f"fixtures/labeled/{rel}"],
                subtype="clean_plus_artifact",
                notes="Hard marker present; hard-pass = FN",
            )
        )

    assert len(cases) == 50, len(cases)
    by_class = {}
    for c in cases:
        by_class[c["label"]["class"]] = by_class.get(c["label"]["class"], 0) + 1

    corpus = {
        "schema_version": 3,
        "purpose": "Labeled product-value bench (not Airflow volume census)",
        "counts": {
            "total": 50,
            "proper_synthetic_negative": 5,
            "ai_slop_synthetic_positive": 30,
            "mixed_sample": 15,
            "by_label_class": by_class,
        },
        "claim_policy": {
            "primary": "Use this corpus for VERIFIED precision/recall/FP on labeled ground truth",
            "secondary": "Airflow closed-unmerged census is volume context only — not AI-slop catch rate",
        },
        "cases": cases,
    }
    CORPUS.parent.mkdir(parents=True, exist_ok=True)
    CORPUS.write_text(json.dumps(corpus, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {CORPUS} with {len(cases)} cases: {by_class}")


if __name__ == "__main__":
    main()
