package io.github.vaquarkhan.aiv.plugin.licenseheader;

import io.github.vaquarkhan.aiv.model.AIVConfig;
import io.github.vaquarkhan.aiv.model.AIVContext;
import io.github.vaquarkhan.aiv.model.ChangedFile;
import io.github.vaquarkhan.aiv.model.Diff;
import io.github.vaquarkhan.aiv.model.GateResult;
import org.junit.jupiter.api.Test;

import java.nio.file.Paths;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * @author Vaquar Khan
 */
class LicenseHeaderGateTest {

    private static final String ASF_HEADER =
            "/*\n * Licensed to the Apache Software Foundation (ASF) under one\n */\n";

    @Test
    void getId() {
        assertEquals("license-header", new LicenseHeaderGate().getId());
    }

    @Test
    void failsWhenAddedSourceFileHasNoHeader() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("Foo.java", "package a;\nclass Foo {}\n")));
        assertFalse(r.isPassed());
        assertTrue(r.getFindings().stream().anyMatch(f -> "license-header.missing".equals(f.getRuleId())));
    }

    @Test
    void passesWhenAddedFileHasAsfHeader() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("Foo.java", ASF_HEADER + "class Foo {}\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void passesWithSpdxShortForm() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("mod.py", "# SPDX-License-Identifier: Apache-2.0\nx = 1\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void passesWithApacheLicenseUrl() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("a.go",
                "// See http://www.apache.org/licenses/LICENSE-2.0 for terms\npackage a\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void passesWithLicensedUnderPhrase() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("a.rb", "# Licensed under the Apache License, Version 2.0\nputs 1\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void ignoresModifiedFiles() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(List.of(
                new ChangedFile("Foo.java", ChangedFile.ChangeType.MODIFIED, "class Foo {}\n"))));
        assertTrue(r.isPassed());
    }

    @Test
    void ignoresGeneratedBySuffix() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("app.min.js", "console.log(1)\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void ignoresNonSourceFiles() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("README.md", "# Title\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void ignoresBlankFiles() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("Empty.java", "   \n")));
        assertTrue(r.isPassed());
    }

    @Test
    void ignoresGeneratedContentMarker() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(added("Parser.java", "// Generated by JavaCC - do not edit\nclass Parser {}\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void handlesLongFileWithHeaderNearTop() {
        var gate = new LicenseHeaderGate();
        String body = "x".repeat(9000);
        var r = gate.evaluate(ctx(added("Big.java", ASF_HEADER + "class Big { String s = \"" + body + "\"; }\n")));
        assertTrue(r.isPassed());
    }

    @Test
    void reportsEachMissingFile() {
        var gate = new LicenseHeaderGate();
        var r = gate.evaluate(ctx(List.of(
                new ChangedFile("A.java", ChangedFile.ChangeType.ADDED, "class A {}\n"),
                new ChangedFile("B.py", ChangedFile.ChangeType.ADDED, "x = 1\n"))));
        assertFalse(r.isPassed());
        assertEquals(2, r.getFindings().size());
    }

    // ---- helpers ----

    private static List<ChangedFile> added(String path, String content) {
        return List.of(new ChangedFile(path, ChangedFile.ChangeType.ADDED, content));
    }

    private static AIVContext ctx(List<ChangedFile> files) {
        var diff = new Diff("main", "HEAD", files, "");
        var config = new AIVConfig(List.of(), Map.of());
        return new AIVContext(Paths.get("."), diff, config);
    }
}
