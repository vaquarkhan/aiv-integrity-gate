package io.github.vaquarkhan.aiv.plugin.licenseheader;

import io.github.vaquarkhan.aiv.model.AIVConfig;
import io.github.vaquarkhan.aiv.model.AIVContext;
import io.github.vaquarkhan.aiv.model.ChangedFile;
import io.github.vaquarkhan.aiv.model.Diff;
import org.junit.jupiter.api.Test;

import java.nio.file.Paths;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Repository-specific configuration of the license-header gate. */
class LicenseHeaderGateConfigTest {

    private static AIVContext ctx(Map<String, Object> cfg, String path, String content) {
        var config = new AIVConfig(List.of(new AIVConfig.GateConfig(LicenseHeaderGate.ID, true, cfg)), Map.of());
        return new AIVContext(Paths.get("."), new Diff("main", "HEAD",
                List.of(new ChangedFile(path, ChangedFile.ChangeType.ADDED, content)), ""), config);
    }

    @Test
    void customHeaderMarkersReplaceApacheDefault() {
        var gate = new LicenseHeaderGate();
        String mit = "// SPDX-License-Identifier: MIT\nclass A {}\n";
        assertFalse(gate.evaluate(ctx(Map.of(), "A.java", mit)).isPassed());
        Map<String, Object> cfg = Map.of("header_markers", List.of("SPDX-License-Identifier: MIT", "Copyright Example Corp"));
        assertTrue(gate.evaluate(ctx(cfg, "A.java", mit)).isPassed());
        assertTrue(gate.evaluate(ctx(cfg, "B.java", "/* copyright example corp */\nclass B {}\n")).isPassed());
        assertFalse(gate.evaluate(ctx(cfg, "C.java", "class C {}\n")).isPassed());
    }

    @Test
    void generatedMarkersAndExcludePathsSkipFiles() {
        var gate = new LicenseHeaderGate();
        Map<String, Object> cfg = Map.of("generated_markers", List.of("AUTOGEN"), "exclude_paths", List.of("vendor/**"));
        assertTrue(gate.evaluate(ctx(cfg, "A.java", "// AUTOGEN file\nclass A {}\n")).isPassed());
        // the default "generated by" marker no longer applies once the list is replaced
        assertFalse(gate.evaluate(ctx(cfg, "B.java", "// generated by tool\nclass B {}\n")).isPassed());
        assertTrue(gate.evaluate(ctx(cfg, "vendor/lib/C.java", "class C {}\n")).isPassed());
    }

    @Test
    void fileExtensionsLimitScope() {
        var gate = new LicenseHeaderGate();
        assertFalse(gate.evaluate(ctx(Map.of(), "a.py", "print(1)\n")).isPassed());
        assertTrue(gate.evaluate(ctx(Map.of("file_extensions", List.of(".java")), "a.py", "print(1)\n")).isPassed());
        assertFalse(gate.evaluate(ctx(Map.of("languages", List.of("python")), "a.py", "print(1)\n")).isPassed());
    }

    @Test
    void settingsHelpers() {
        assertEquals(List.of("x"), LicenseHeaderGate.Settings.strings(Arrays.asList(" x ", null, "")));
        assertTrue(LicenseHeaderGate.Settings.strings("nope").isEmpty());
        var s = LicenseHeaderGate.Settings.from(Map.of());
        assertEquals(4, s.headerMarkers().size());
        assertEquals(3, s.generatedMarkers().size());
        assertTrue(s.excludePaths().isEmpty());
    }
}
