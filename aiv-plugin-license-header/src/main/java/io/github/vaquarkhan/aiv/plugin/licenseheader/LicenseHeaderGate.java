package io.github.vaquarkhan.aiv.plugin.licenseheader;

import io.github.vaquarkhan.aiv.model.AIVContext;
import io.github.vaquarkhan.aiv.model.ChangedFile;
import io.github.vaquarkhan.aiv.model.Finding;
import io.github.vaquarkhan.aiv.model.GateResult;
import io.github.vaquarkhan.aiv.port.QualityGate;
import io.github.vaquarkhan.aiv.util.FileExtensions;
import io.github.vaquarkhan.aiv.util.PathFilter;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Diff-scoped Apache license-header check.
 *
 * <p>Apache projects require the Apache license header on source files (ASF source-header policy).
 * Apache RAT enforces this across the whole tree at release time; this gate shifts the same check
 * left to the pull request, but only for <em>newly added</em> source files, so it never re-flags
 * pre-existing files a PR merely touches.
 *
 * <p>Precision-first: it inspects only added files with a recognized source extension, skips
 * generated artifacts (by suffix and by generated-marker content), and skips blank files. When in
 * doubt it passes. It looks at the head of the file for the standard Apache header text or the SPDX
 * short form.
 *
 * @author Vaquar Khan
 */
public final class LicenseHeaderGate implements QualityGate {

    /** Gate id used in {@code .aiv/config.yaml} and reports. */
    public static final String ID = "license-header";

    private static final int HEAD_CHARS = 4096;

    private static final Set<String> SOURCE_EXTENSIONS = Set.of(
            ".java", ".py", ".js", ".ts", ".jsx", ".tsx", ".go", ".rs", ".kt", ".kts",
            ".scala", ".c", ".cpp", ".cc", ".h", ".hpp", ".rb", ".sh", ".bash", ".groovy");

    private static final String[] GENERATED_SUFFIXES = {
            ".min.js", ".min.css", ".min.map", ".bundle.js", ".chunk.js", ".js.map", ".css.map"};

    private static final String[] HEADER_MARKERS = {
            "licensed to the apache software foundation",
            "www.apache.org/licenses/license-2.0",
            "licensed under the apache license",
            "spdx-license-identifier: apache-2.0"};

    @Override
    public String getId() {
        return ID;
    }

    /**
     * Per-repository settings read from the gate's {@code config} map.
     *
     * <pre>
     * - id: license-header
     *   config:
     *     header_markers: ["Copyright (c) Example Corp", "SPDX-License-Identifier: MIT"]  # any one satisfies
     *     generated_markers: ["@generated", "do not edit"]   # files whose head contains one are skipped
     *     file_extensions: [.java, .kt, .py]                 # files that must carry a header
     *     exclude_paths: ["**&#47;vendor/**"]                 # glob patterns never checked
     * </pre>
     * Defaults are the Apache 2.0 header or SPDX short form, the common generated-code markers,
     * and the source extensions listed in this class.
     */
    record Settings(List<String> headerMarkers, List<String> generatedMarkers, Set<String> extensions,
                    List<String> excludePaths) {

        static Settings from(Map<String, Object> cfg) {
            List<String> headers = lower(strings(cfg.get("header_markers")));
            List<String> generated = lower(strings(cfg.get("generated_markers")));
            Set<String> exts = cfg.containsKey("file_extensions") || cfg.containsKey("languages")
                    ? FileExtensions.fromConfig(cfg) : SOURCE_EXTENSIONS;
            return new Settings(headers.isEmpty() ? List.of(HEADER_MARKERS) : headers,
                    generated.isEmpty() ? List.of("generated by", "do not edit", "@generated") : generated,
                    exts, strings(cfg.get("exclude_paths")));
        }

        static List<String> strings(Object v) {
            List<String> out = new ArrayList<>();
            if (v instanceof List<?> list) {
                for (Object o : list) {
                    if (o != null && !o.toString().isBlank()) {
                        out.add(o.toString().trim());
                    }
                }
            }
            return out;
        }

        private static List<String> lower(List<String> in) {
            List<String> out = new ArrayList<>();
            for (String s : in) {
                out.add(s.toLowerCase());
            }
            return out;
        }
    }

    @Override
    public GateResult evaluate(AIVContext context) {
        List<String> failures = new ArrayList<>();
        List<Finding> findings = new ArrayList<>();
        Settings s = Settings.from(context.getConfig().findGate(ID).map(g -> g.getConfig()).orElse(Map.of()));

        for (ChangedFile f : context.getDiff().getChangedFiles()) {
            if (f.getChangeType() != ChangedFile.ChangeType.ADDED) {
                continue;
            }
            String path = f.getPath();
            if (!FileExtensions.matches(path, s.extensions()) || isGeneratedPath(path)
                    || PathFilter.isExcluded(path, s.excludePaths())) {
                continue;
            }
            String content = f.getContent();
            if (content == null || content.isBlank()) {
                continue;
            }
            String head = headOf(content);
            if (containsAny(head, s.generatedMarkers()) || containsAny(head, s.headerMarkers())) {
                continue;
            }
            String msg = "Missing license header in new file " + path + " (expected one of: "
                    + String.join(" | ", s.headerMarkers()) + ")";
            failures.add(msg);
            findings.add(Finding.atLine("license-header.missing", path, 1, msg));
        }

        if (failures.isEmpty()) {
            return GateResult.pass(ID);
        }
        return GateResult.fail(ID, String.join("\n", failures), findings);
    }

    private static String headOf(String content) {
        String slice = content.length() > HEAD_CHARS ? content.substring(0, HEAD_CHARS) : content;
        return slice.toLowerCase();
    }

    private static boolean containsAny(String head, List<String> markers) {
        for (String marker : markers) {
            if (head.contains(marker)) {
                return true;
            }
        }
        return false;
    }

    private static boolean isGeneratedPath(String path) {
        String lower = path.toLowerCase();
        for (String suffix : GENERATED_SUFFIXES) {
            if (lower.endsWith(suffix)) {
                return true;
            }
        }
        return false;
    }

}
